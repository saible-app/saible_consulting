extension on String {
  String alpha2Emoji() => replaceAllMapped(
    RegExp('[A-Z]'), (m) => String.fromCharCode(m.group(0)!.codeUnitAt(0) + 127397)
  );
}

/// Convenience extensions on [Iso3166Country].
extension CountryExtension on Iso3166Country {
  /// Returns the flag emoji corresponding to the country's [alpha2] code.
  String flagEmoji() => alpha2.alpha2Emoji();

  /// Returns a list of search terms for matching this country, including
  /// [alpha2], [alpha3], localized name, and any [extras].
  List<String> searchTerms(BuildContext context) => [alpha2, alpha3, tr(context), ...extras];

  /// Returns a list of search terms including [searchTerms] and telephone calling codes.
  List<String> phoneSearchTerms(BuildContext context) => [
    ...searchTerms(context),
    phoneCode.toString(),
    '+$phoneCode',
  ];
}
